/** 取词，支持 {name} 占位替换 */
export function translate(lang, key, vars) {
  const dict = STRINGS[lang] || STRINGS.zh;
  let s = dict[key];
  if (s === undefined) s = STRINGS.zh[key] !== undefined ? STRINGS.zh[key] : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}
